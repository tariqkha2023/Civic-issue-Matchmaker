import {test,expect} from '@playwright/test';
const password='fixture demo password';
async function login(page,email){await page.goto('/#/login');await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill(password);await page.getByRole('button',{name:'Login',exact:true}).last().click();await expect(page.getByRole('heading',{name:'Discover civic-tech issues'})).toBeVisible();}
async function overflow(page,width){expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);}

test('contributor discovers source issues, tracks work, rates relevance and exports data',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await login(page,'volunteer@civic.demo');
 await page.getByRole('button',{name:'My profile',exact:true}).click();
 await page.getByLabel('Skills (comma separated)',{exact:true}).fill('Python');
 await page.getByLabel('Interests / civic topics (comma separated)').fill('Humanitarian mapping');
 await page.getByLabel('Weekly availability (hours)').fill('3');
 await page.getByRole('button',{name:'Save profile',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Profile saved');
 await page.getByRole('button',{name:'Projects',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Civic projects'})).toBeVisible();
 const project=page.locator('article').filter({has:page.getByRole('heading',{name:'HOT Tasking Manager',exact:true})});
 await project.getByRole('button',{name:'Browse issues'}).click();
 await page.getByLabel('Search',{exact:true}).fill('Improve Python mapping API');
 await page.getByRole('button',{name:'Improve Python mapping API',exact:true}).click();
 await expect(page.getByRole('heading',{name:'AI-extracted requirements'})).toBeVisible();
 await expect(page.locator('q').filter({hasText:'Python'})).toBeVisible();
 await expect(page.getByText('testing · AI inferred',{exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Open on GitHub'})).toHaveAttribute('href','https://github.com/hotosm/tasking-manager/issues/1');
 if(await page.getByRole('button',{name:'Unsave issue',exact:true}).count())await page.getByRole('button',{name:'Unsave issue',exact:true}).click();
 await page.getByRole('button',{name:'Save issue',exact:true}).click();
 await expect(page.getByRole('button',{name:'Unsave issue',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Track contribution',exact:true}).click();
 await expect(page.getByRole('button',{name:'Tracking contribution',exact:true})).toBeVisible();
 await page.getByLabel('Feedback explanation (optional)').fill('Relevant to my mapping interests.');
 await page.getByRole('button',{name:'Relevant',exact:true}).click();
 await expect(page.getByText('Your current rating: Relevant.',{exact:false})).toBeVisible();
 await overflow(page,info.project.use.viewport.width);
 await page.getByRole('button',{name:'My contributions',exact:true}).click();
 const current=page.locator('article').filter({has:page.getByRole('heading',{name:'Improve Python mapping API',exact:true})}).filter({has:page.getByRole('button',{name:'Start work',exact:true})}).last();
 await current.getByRole('button',{name:'Start work',exact:true}).click();
 const working=page.locator('article').filter({has:page.getByRole('button',{name:'Mark contribution complete',exact:true})}).last();
 await working.getByLabel('GitHub submission URL').fill('https://github.com/hotosm/tasking-manager/pull/123');
 await working.getByLabel('Contribution note').fill('Prepared a mapping API improvement.');
 await working.getByRole('button',{name:'Add submission',exact:true}).click();
 const submitted=page.locator('article').filter({has:page.getByRole('button',{name:'Mark contribution complete',exact:true})}).last();
 await submitted.getByRole('button',{name:'Mark contribution complete',exact:true}).click();
 await expect(page.getByText('Self-reported; no upstream acceptance verified').last()).toBeVisible();
 await page.reload();await expect(page.getByRole('heading',{name:'My contributions'})).toBeVisible();
 await page.getByRole('button',{name:'Account settings',exact:true}).click();
 await page.getByLabel('New matching issues',{exact:true}).uncheck();
 await page.getByRole('button',{name:'Save preferences',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Preferences saved');
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download my data'}).click();
 expect((await download).suggestedFilename()).toBe('civic-account-export.json');
 await overflow(page,info.project.use.viewport.width);
 await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0);});
 await page.screenshot({path:info.outputPath('account.png'),fullPage:true});
 expect(errors).toEqual([]);
});

